register = template.Library()


@register.filter
def fcfa(valeur):
    """12500 → « 12 500 FCFA »"""
    try:
        montant = int(valeur)
    except (TypeError, ValueError):
        return valeur
    return f"{montant:,}".replace(',', ' ') + ' ' + settings.BOUTIQUE['DEVISE']


@register.simple_tag
def lien_whatsapp(message=''):
    """Lien wa.me vers le numéro WhatsApp Business, avec un message déjà écrit."""
    url = 'https://wa.me/' + settings.BOUTIQUE['WHATSAPP']
    return url + ('?text=' + quote(message) if message else '')


