@register.simple_tag
def icone(nom, taille=22):
    if nom == 'whatsapp':
        return format_html(
            '<svg width="{}" height="{}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">{}</svg>',
            taille, taille, mark_safe(_WHATSAPP),
        )
    return format_html(
        '<svg width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" '
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        taille, taille, mark_safe(_TRACES.get(nom, '')),
    )
